#!/usr/bin/env python3
"""Assemble copyq_ref.cu from the real engine source (backend-gpu.cu, decode.cuh, moe.cuh, kernels.cuh).

The extracted blocks are copied as bytes (line endings included) and located by markers; if a marker is missing, matches
more than once, or the block does not look as expected, this script exits non-zero without writing the output.
Usage: python extract.py [--src <src/code/gpu dir>] [--out copyq_ref.cu]
"""
import argparse, hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def fail(msg):
    sys.stderr.write("extract.py: FAIL: " + msg + "\n")
    sys.exit(1)


def read_lines(path):
    if not os.path.isfile(path):
        fail("source file not found: " + path)
    with open(path, "rb") as f:
        parts = f.read().split(b"\n")
    lines = [p + b"\n" for p in parts[:-1]]
    if parts[-1]:
        lines.append(parts[-1])
    return lines


def find_one(lines, pred, what, path):
    hits = [i for i, l in enumerate(lines) if pred(l)]
    if len(hits) != 1:
        fail("%s: expected exactly one match for %s, found %d" % (path, what, len(hits)))
    return hits[0]


def block(path, lines, what, start_pred, end_pred=None):
    """Return (first_line_no, last_line_no, bytes) of a 1-based inclusive range."""
    s = find_one(lines, start_pred, what + " (start marker)", path)
    e = s
    if end_pred is not None:
        e = None
        for i in range(s, len(lines)):
            if end_pred(lines[i]):
                e = i
                break
        if e is None:
            fail("%s: end marker for %s not found after line %d" % (path, what, s + 1))
    data = b"".join(lines[s:e + 1])
    return dict(path=path, what=what, first=s + 1, last=e + 1, data=data)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=os.path.normpath(os.path.join(HERE, "..", "..", "..", "code", "gpu")))
    ap.add_argument("--out", default=os.path.join(HERE, "copyq_ref.cu"))
    a = ap.parse_args()

    p_back = os.path.join(a.src, "backend-gpu.cu")
    p_dec = os.path.join(a.src, "decode.cuh")
    p_moe = os.path.join(a.src, "moe.cuh")
    p_ker = os.path.join(a.src, "kernels.cuh")
    back, dec, moe, ker = (read_lines(p) for p in (p_back, p_dec, p_moe, p_ker))
    sw = lambda s: (lambda l: l.startswith(s))

    B = {}
    B["check"] = block(p_ker, ker, "CHECK macro", sw(b"#define CHECK(x) do {"))
    B["enum_raw"] = block(p_moe, moe, "enum with EXPERT_RAW",
                          lambda l: l.startswith(b"enum {") and b"EXPERT_RAW = 17547264" in l)
    B["enum_cards"] = block(p_back, back, "enum MAX_CARDS", sw(b"enum { MAX_CARDS = 8,"))
    B["act_gate"] = block(p_dec, dec, "act_gate", sw(b"static inline void act_gate()"))
    B["pfjob"] = block(p_back, back, "struct PfJob", sw(b"struct PfJob {"), sw(b"};"))
    B["pfqueue"] = block(p_back, back, "struct PfQueue", sw(b"struct PfQueue {"))
    B["pfq"] = block(p_back, back, "pfq()", sw(b"static PfQueue &pfq(int i)"))
    B["pf_enqueue"] = block(p_back, back, "pf_enqueue", sw(b"static void pf_enqueue(const PfJob &j)"),
                            lambda l: l.rstrip(b"\r\n") == b"}")

    # The glue stubs state-only Pending/Arrival/Rel; fail if the originals stop starting with `std::atomic<int> state;`.
    for name, path, lines in (("Pending", p_dec, dec), ("Arrival", p_dec, dec), ("Rel", p_back, back)):
        i = find_one(lines, sw(("struct %s { std::atomic<int> state;" % name).encode()), "original struct " + name, path)
        _ = i
    # Sanity of the extracted blocks.
    pe = B["pf_enqueue"]["data"]
    if pe.count(b"{") != pe.count(b"}"):
        fail("pf_enqueue block has unbalanced braces (%d vs %d)" % (pe.count(b"{"), pe.count(b"}")))
    for need in (b"pread(", b"cudaMemcpyAsync", b"act_gate();", b"jb.arr->state.store(1", b"jb.wb->state.store(1", b"jb.p->state.store(1"):
        if need not in pe:
            fail("pf_enqueue block lacks expected text %r (source changed?)" % need)
    if b"(size_t)EXPERT_RAW" not in pe:
        fail("pf_enqueue block no longer uses EXPERT_RAW as expected")

    manifest = []
    for k in ("check", "enum_raw", "enum_cards", "act_gate", "pfjob", "pfqueue", "pfq", "pf_enqueue"):
        b = B[k]
        rel = os.path.relpath(b["path"], a.src).replace("\\", "/")
        manifest.append("//   %-12s %s lines %d-%d sha256 %s" % (k, rel, b["first"], b["last"], hashlib.sha256(b["data"]).hexdigest()[:16]))

    def glue(s):
        return s.replace("\r\n", "\n").replace("\n", "\r\n").encode()

    def ext(k):
        b = B[k]
        return glue("// ---- extracted verbatim: %s lines %d-%d (%s)\n" % (os.path.basename(b["path"]), b["first"], b["last"], b["what"])) + b["data"]

    out = b""
    out += glue("""// GENERATED by extract.py from the engine sources; do not edit. Reference implementation of copyq.h.
// Extracted blocks (kept byte-for-byte, including CRLF):
""" + "\n".join(manifest) + """
#include <algorithm>
#include <atomic>
#include <cerrno>
#include <condition_variable>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <deque>
#include <memory>
#include <mutex>
#include <thread>
#include <sys/types.h>
#include <unistd.h>
#include <cuda_runtime.h>
#include "copyq.h"

""")
    out += ext("check") + ext("enum_raw") + ext("enum_cards")
    out += glue("""
// ---- glue (written for the reference; see NOTES.md)
static_assert(sizeof(std::atomic<int>) == 4 && std::atomic<int>::is_always_lock_free, "the contract's int* flags must be lock-free 4-byte atomics");
// Only .state is ever touched by the extracted worker; the caller's int is reinterpreted as it (originals also carry a RAM slot pointer, never read there).
struct Pending { std::atomic<int> state; };
struct Arrival { std::atomic<int> state; };
struct Rel { std::atomic<int> state; };
static_assert(sizeof(Pending) == 4 && sizeof(Arrival) == 4 && sizeof(Rel) == 4, "state-only stubs must overlay a single int");
static int g_cards = 0, g_readers = 16;
static bool g_prefill = false;
// Stands for the original `static unsigned char *g_slab[93]`: the engine fills that table after start-up, so the reference reads the caller's table at use time.
struct SlabTable { const unsigned char *const *t = nullptr; unsigned char *operator[](int i) const { return const_cast<unsigned char *>(t[i]); } };
static SlabTable g_slab;
// Stands for the original `static std::atomic<int> g_act_hold(0)`: here the atomic lives in the caller (cq_config.act_hold).
struct ActHold { const std::atomic<int> *p = nullptr; int load(std::memory_order o) const { return p ? p->load(o) : 0; } };
static ActHold g_act_hold;
""")
    out += ext("act_gate") + glue("\n") + ext("pfjob") + ext("pfqueue") + ext("pfq") + glue("\n") + ext("pf_enqueue")
    out += glue("""
// ---- glue: C entry points of copyq.h
extern "C" void cq_init(const cq_config *cfg)
{
    if (cfg->expert_raw != (size_t)EXPERT_RAW) { fprintf(stderr, "cq_init: expert_raw %zu != compiled EXPERT_RAW %zu\\n", cfg->expert_raw, (size_t)EXPERT_RAW); exit(1); }
    g_readers = cfg->readers; g_cards = cfg->cards; g_prefill = cfg->prefill != 0;
    g_slab.t = cfg->slab;
    g_act_hold.p = reinterpret_cast<const std::atomic<int> *>(cfg->act_hold);
}

extern "C" void cq_enqueue(const cq_job *c)
{
    PfJob j;
    j.fd = c->fd; j.off = c->off; j.slot = c->slot; j.p = reinterpret_cast<Pending *>(c->p_state); j.layer = c->layer;
    j.kind = c->kind; j.dev = c->dev; j.dst = c->dst; j.host_src = const_cast<unsigned char *>(c->host_src); j.victim_host = c->victim_host;
    j.wb = reinterpret_cast<Pending *>(c->wb_state);
    if (c->arr_state) j.arr = std::shared_ptr<Arrival>(std::shared_ptr<void>(), reinterpret_cast<Arrival *>(c->arr_state));
    if (c->rel_state) j.rel = std::shared_ptr<Rel>(std::shared_ptr<void>(), reinterpret_cast<Rel *>(c->rel_state));
    pf_enqueue(j);
}
""")

    # Verify the output holds every extracted block verbatim, then write.
    for k, b in B.items():
        if out.count(b["data"]) != 1:
            fail("self-check: block %s not present exactly once in the assembled output" % k)
    with open(a.out, "wb") as f:
        f.write(out)
    print("wrote %s (%d bytes)" % (a.out, len(out)))
    print("\n".join(m[3:] for m in manifest))


if __name__ == "__main__":
    main()
