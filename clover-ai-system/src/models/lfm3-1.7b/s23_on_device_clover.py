    clean_speech = re.sub(r"[*`#_~\[\]()<>]", " ", text or "Hello from Clover on your Samsung Galaxy S23.")
    clean_speech = re.sub(r"\s+", " ", clean_speech).strip()[:360]
    if not clean_speech:
        clean_speech = "Here is your audio response from Clover."

