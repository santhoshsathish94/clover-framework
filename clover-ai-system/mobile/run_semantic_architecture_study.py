class Lfm3Omni24LayerInspector:
    """Runs all 24 Tri-Hybrid layers of LFM3-Omni-2B via `liblfm3_cpu_engine.so` (`lfm3_forward_all_layers`) and captures every layer's hidden state."""

    def __init__(self, pruned_dir: Path, tok_path: Path):
        self.pruned_dir = pruned_dir
        self.tok = Tokenizer.from_file(str(tok_path))
        global_dir = pruned_dir / "global-0"
        emb_raw = np.frombuffer((global_dir / "embed_tokens.bf16.bin").read_bytes(), dtype=np.uint16).copy()
        self.emb_w = torch.from_numpy(emb_raw).view(torch.bfloat16).reshape(128000, 2048)

        so_path = BASE_S23 / "liblfm3_cpu_engine.so"
        self.lib = ctypes.CDLL(str(so_path))
        self.lib.lfm3_engine_init.argtypes = [ctypes.c_char_p, ctypes.c_int]
        self.lib.lfm3_engine_init.restype = ctypes.c_int
        self.lib.lfm3_forward_all_layers.argtypes = [
            ctypes.POINTER(ctypes.c_int),
            ctypes.c_int,
            ctypes.POINTER(ctypes.c_float),
            ctypes.POINTER(ctypes.c_float),
        ]
        self.lib.lfm3_forward_all_layers.restype = ctypes.c_float
        rc = self.lib.lfm3_engine_init(str(pruned_dir).encode("utf-8"), 1)
        if rc != 0:
            raise RuntimeError(f"lfm3_engine_init failed: rc={rc}")

        self.layer_kinds = []
        for idx in range(24):
            idx_bytes = (pruned_dir / f"trunk-{idx}" / "index.bin").read_bytes()
            _, _, _, lkind = struct.unpack("<8sIII", idx_bytes[:20])
            self.layer_kinds.append("conv" if lkind == 0 else ("sliding_gqa" if lkind == 1 else "full_gqa"))

    @torch.no_grad()
    def forward_all_layers(self, text: str, span_word: str | None = None) -> dict[str, Any]:
        """
        Returns per-layer vector representations `[25, 2048]` (layer 0 = embedding, layers 1..24 = blocks 0..23,
        plus `final_norm` = after `embedding_norm`).
        If `span_word` is given, isolates the token span overlapping the last occurrence of `span_word`
        (matching Paper 1 Appendix C.4 token-span isolation); otherwise uses the last token position.
        """
        enc = self.tok.encode(text, add_special_tokens=False)
        ids = enc.ids
        offsets = enc.offsets
        seq_len = len(ids)

        # Locate span tokens if span_word is provided
        span_indices = [seq_len - 1]
        if span_word:
            idx_char = text.lower().rfind(span_word.lower())
            if idx_char >= 0:
                end_char = idx_char + len(span_word)
                matched = [
                    i for i, (s_off, e_off) in enumerate(offsets)
                    if e_off > s_off and max(s_off, idx_char) < min(e_off, end_char)
                ]
                if matched:
                    span_indices = matched

        c_ids = (ctypes.c_int * seq_len)(*ids)
        all_layers = np.zeros((25, seq_len, 2048), dtype=np.float32)
        final_norm = np.zeros((seq_len, 2048), dtype=np.float32)
        self.lib.lfm3_forward_all_layers(
            c_ids,
            seq_len,
            all_layers.ctypes.data_as(ctypes.POINTER(ctypes.c_float)),
            final_norm.ctypes.data_as(ctypes.POINTER(ctypes.c_float)),
        )
        span_vecs = all_layers[:, span_indices, :].mean(axis=1)  # [25, 2048]
        last_vecs = all_layers[:, -1, :]                        # [25, 2048]
        final_span_vec = final_norm[span_indices, :].mean(axis=0)
        final_last_vec = final_norm[-1, :]
        return {
            "span_vecs": span_vecs,
            "last_vecs": last_vecs,
            "final_norm_span": final_span_vec,
            "final_norm_last": final_last_vec,
        }


