            test_mask = np.zeros(n, dtype=bool)
            for c_id in (0, 1, 2):
                c_indices = np.where(y == c_id)[0]
                test_mask[c_indices[fold * 2 : (fold + 1) * 2]] = True
            train_mask = ~test_mask

