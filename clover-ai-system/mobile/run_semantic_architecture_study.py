    labels_str = [lbl for _, lbl in ROUTING_BENCHMARK_36]
    label_map = {"concept_only": 0, "safe_tool": 1, "risky_ask": 2}
    y = np.array([label_map[lbl] for lbl in labels_str], dtype=np.int64)
    n = len(prompts)

    # Extract all 24 layers' last-token representations for the 36 prompts
    H_layers = np.zeros((25, n, 2048), dtype=np.float32)
    for i, p in enumerate(prompts):
        chat_p = f"<|startoftext|><|im_start|>user\n{p}<|im_end|>\n<|im_start|>assistant\n"
        H_layers[:, i, :] = inspector.forward_all_layers(chat_p)["last_vecs"]

