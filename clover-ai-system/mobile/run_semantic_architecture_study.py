@torch.no_grad()
def encode_with_embedder(embedders: dict[str, Any], name: str, texts: list[str]) -> np.ndarray:
    if name == "subword_hash":
        return embedders["subword_hash"].encode(texts)
    tok, mod = embedders[name]
    inp = tok(texts, padding=True, truncation=True, max_length=256, return_tensors="pt")
    out = mod(**inp)
    if name == "bge_small":
        vecs = out.last_hidden_state[:, 0]
    else:
        mask = inp["attention_mask"].unsqueeze(-1).float()
        vecs = (out.last_hidden_state * mask).sum(dim=1) / mask.sum(dim=1).clamp(min=1e-9)
    vecs = F.normalize(vecs, p=2, dim=-1)
    return vecs.cpu().numpy()


def cosine_sim_matrix(X: np.ndarray, mean_center: bool = False) -> np.ndarray:
    V = X.astype(np.float64).copy()
    if mean_center:
        V = V - V.mean(axis=0, keepdims=True)
    norms = np.linalg.norm(V, axis=1, keepdims=True)
    V = V / np.clip(norms, 1e-12, None)
    return V @ V.T


def upper_tri_vec(S: np.ndarray) -> np.ndarray:
    iu = np.triu_indices(S.shape[0], k=1)
    return S[iu]


def pearson_r(a: np.ndarray, b: np.ndarray) -> float:
    a0 = a - a.mean()
    b0 = b - b.mean()
    denom = np.linalg.norm(a0) * np.linalg.norm(b0)
    return float(np.dot(a0, b0) / denom) if denom > 1e-12 else 0.0


def nn_overlap_at_k(S_a: np.ndarray, S_b: np.ndarray, k: int = 5) -> float:
    n = S_a.shape[0]
    overlaps = []
    for i in range(n):
        row_a = S_a[i].copy()
        row_b = S_b[i].copy()
        row_a[i] = -np.inf
        row_b[i] = -np.inf
        top_a = set(np.argsort(row_a)[-k:])
        top_b = set(np.argsort(row_b)[-k:])
        overlaps.append(len(top_a & top_b) / float(k))
    return float(np.mean(overlaps))


