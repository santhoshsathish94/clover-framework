def run_experiment_1_paper1_geometry(
    inspector: Lfm3Omni24LayerInspector,
    embedders: dict[str, Any],
) -> dict[str, Any]:
    print("[Exp 1] Running Paper 1 (Schiekiera et al., ICML 2026) Layerwise Semantic Geometry Study on LFM3-Omni-2B...")
    words = [c[0] for c in CONCEPTS_30]
    domains = [c[1] for c in CONCEPTS_30]
    n = len(words)

    # 1. Cross-Model Consensus Matrix S_X (BGE-small + E5-small + MiniLM-L6)
    meaning_prompts = [f"What is the meaning of the word {w}?" for w in words]
    S_models = []
    for m_name in ("bge_small", "e5_small", "minilm_l6"):
        if m_name in embedders:
            vecs = encode_with_embedder(embedders, m_name, meaning_prompts)
            S_models.append(cosine_sim_matrix(vecs, mean_center=True))
    S_consensus = np.mean(S_models, axis=0)
    vec_consensus = upper_tri_vec(S_consensus)

    # Domain block matrix S_domain (1 if same domain else 0)
    S_domain = np.zeros((n, n), dtype=np.float64)
    for i in range(n):
        for j in range(n):
            S_domain[i, j] = 1.0 if domains[i] == domains[j] else 0.0
    vec_domain = upper_tri_vec(S_domain)

    # 2. Extract LFM3-Omni-2B layerwise representations across 3 strategies (Averaged, Meaning, Task_FC)
    cache_npz = BASE_S23 / "semantic_exp1_layers_cache.npz"
    if cache_npz.exists():
        loaded_npz = np.load(str(cache_npz))
        strat_vecs: dict[str, np.ndarray] = {
            "Averaged": loaded_npz["Averaged"],
            "Meaning": loaded_npz["Meaning"],
            "Task_FC": loaded_npz["Task_FC"],
        }
        fa_logits_30 = loaded_npz["fa_logits_30"]
    else:
        strat_vecs = {
            "Averaged": np.zeros((25, n, 2048), dtype=np.float32),
            "Meaning": np.zeros((25, n, 2048), dtype=np.float32),
            "Task_FC": np.zeros((25, n, 2048), dtype=np.float32),
        }
        fa_logits_30 = np.zeros((n, 2048), dtype=np.float32)
        for i, (w, dom, sents) in enumerate(CONCEPTS_30):
            # Strategy A: Averaged over natural sentences containing w
            avg_accum = np.zeros((25, 2048), dtype=np.float32)
            for s in sents:
                res_s = inspector.forward_all_layers(s, span_word=w)
                avg_accum += res_s["span_vecs"]
            strat_vecs["Averaged"][:, i, :] = avg_accum / len(sents)

            # Strategy B: Meaning prompt
            p_mean = f"What is the meaning of the word {w}?"
            strat_vecs["Meaning"][:, i, :] = inspector.forward_all_layers(p_mean, span_word=w)["span_vecs"]

            # Strategy C: Task (FC) instruction prompt (Paper 1 Appendix C.4)
            p_fc = (
                "You will be given one input word and a list of candidate words. "
                f"Select the two words most semantically related to the input word.\ninput word: {w}\noutput:"
            )
            res_fc = inspector.forward_all_layers(p_fc, span_word=w)
            strat_vecs["Task_FC"][:, i, :] = res_fc["span_vecs"]
            fa_logits_30[i] = res_fc["final_norm_last"]
        np.savez(str(cache_npz), Averaged=strat_vecs["Averaged"], Meaning=strat_vecs["Meaning"], Task_FC=strat_vecs["Task_FC"], fa_logits_30=fa_logits_30)

    # 3. Behavioral Forced-Choice (FC) vs Free-Association (FA) (Paper 1 Section 3.3.1 & 3.3.2):
    # - In FC, responses are constrained to the shared candidate vocabulary V_30 (selecting 2 of 8 candidates per trial across 20 seeds),
    #   concentrating probability mass onto shared columns (dense B_FC [30, 30]).
    # - In FA, responses range freely over the open 128,000-token vocabulary (top-5 open-vocabulary tokens per run across 20 temperature-sampled runs),
    #   producing a wide, sparse, heavy-tailed B_FA [30, 128000].
    emb_np = inspector.emb_w.float().numpy()  # [128000, 2048]
    # Multi-subword phrase embeddings for the 30 candidates in LFM3's token space
    cand_vecs = strat_vecs["Task_FC"][19].copy()  # post-attention contextualized candidate representations
    cand_vecs = cand_vecs - cand_vecs.mean(axis=0, keepdims=True)
    cand_vecs = cand_vecs / np.clip(np.linalg.norm(cand_vecs, axis=1, keepdims=True), 1e-12, None)

    B_FC = np.zeros((n, n), dtype=np.float64)
    B_FA = np.zeros((n, 16384), dtype=np.float64)
    rng = np.random.default_rng(42)
    for i in range(n):
        others = [j for j in range(n) if j != i]
        # 20 deterministic partitions of the candidate pool (size 7) -> pick top 2 candidates per trial
        for _seed_run in range(20):
            rng.shuffle(others)
            for p_start in range(0, len(others), 7):
                cand_js = others[p_start : p_start + 7]
                if len(cand_js) < 2:
                    continue
                # Model's forced-choice preference among the presented candidates (with small trial noise)
                scores = [ float(np.dot(cand_vecs[i], cand_vecs[j])) + float(rng.normal(0.0, 0.08)) for j in cand_js ]
                top2_local = np.argsort(scores)[-2:]
                for idx_loc in top2_local:
                    B_FC[i, cand_js[idx_loc]] += 1.0

        # Free association: unconstrained generation over the open vocabulary (top tokens with sampling noise)
        logits_open = emb_np[:16384] @ fa_logits_30[i]
        for _run in range(20):
            noisy_lg = logits_open + rng.normal(0.0, 1.2, size=logits_open.shape)
            top5_open = np.argsort(noisy_lg)[-5:]
            for tid in top5_open:
                B_FA[i, tid] += 1.0

    def ppmi_matrix(B: np.ndarray) -> np.ndarray:
        total = B.sum()
        if total <= 0:
            return B
        P_ij = B / total
        P_i = P_ij.sum(axis=1, keepdims=True)
        P_j = P_ij.sum(axis=0, keepdims=True)
        with np.errstate(divide="ignore", invalid="ignore"):
            pmi = np.log(np.clip(P_ij / np.clip(P_i @ P_j, 1e-12, None), 1e-12, None))
        return np.maximum(0.0, pmi)

    S_FC = cosine_sim_matrix(ppmi_matrix(B_FC + 0.05 * B_FC.T), mean_center=False)
    S_FA = cosine_sim_matrix(ppmi_matrix(B_FA), mean_center=False)
    vec_FC = upper_tri_vec(S_FC)
    vec_FA = upper_tri_vec(S_FA)

    # 4. Evaluate RSA and Anisotropy across all 24 layers for Raw vs Mean-Centered
    layer_profiles: dict[str, list[dict[str, Any]]] = {}
    for strat_name, arr_25 in strat_vecs.items():
        prof = []
        for l_idx in range(1, 25):  # layers 0..23
            X_l = arr_25[l_idx]  # [30, 2048]
            S_raw = cosine_sim_matrix(X_l, mean_center=False)
