def compute_indra_representation(
    X: np.ndarray,
    anchors: np.ndarray,
    mean_center_mu: np.ndarray | None = None,
    metric: str = "angular",
) -> np.ndarray:
    """
    Computes the V-enriched Yoneda embedding (Indra representation) of samples `X [N, d]`
    with respect to landmarks/anchors `anchors [K, d]`:
      `I_ij = d(X_i, A_j) = arccos(cos(X_i - mu, A_j - mu))`
    Lives in canonical `R^K` regardless of the source dimension `d`!
    """
    Xf = X.astype(np.float64)
    Af = anchors.astype(np.float64)
    if mean_center_mu is not None:
        Xf = Xf - mean_center_mu
        Af = Af - mean_center_mu
    Xn = Xf / np.clip(np.linalg.norm(Xf, axis=1, keepdims=True), 1e-12, None)
    An = Af / np.clip(np.linalg.norm(Af, axis=1, keepdims=True), 1e-12, None)
    cos_sim = np.clip(Xn @ An.T, -1.0, 1.0)
    if metric == "angular":
        return np.arccos(cos_sim)  # Lawvere metric d(x, a) in [0, pi]
    return cos_sim


